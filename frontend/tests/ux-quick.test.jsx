import {render,screen,fireEvent,cleanup,waitFor} from '@testing-library/react';
import {MemoryRouter} from 'react-router-dom';
import {it,expect,vi,afterEach} from 'vitest';
import Rate from '../src/pages/Rate';
import { LanguageProvider } from '../src/context/LanguageProvider';
import { LogoWiggleProvider } from '../src/context/LogoWiggleProvider';
import {animeService} from '../src/services/animeService';
import {ratingService} from '../src/services/ratingService';
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.unstubAllGlobals();});
it('rates an anime card with one star click, outside detail links (no slider)',async()=>{
 vi.stubGlobal('IntersectionObserver',class{observe(){}unobserve(){}disconnect(){}});
 vi.spyOn(animeService,'getAnimeForRating').mockResolvedValue({items:[{id:1,title_romaji:'Fixture',title_korean:'테스트 작품',cover_image_url:'/placeholder-anime.svg',user_rating:0,format:'TV',season_year:2014}],total:1});
 vi.spyOn(animeService,'getAnimeRatingStats').mockResolvedValue({rated:0,watchLater:0,pass:0,averageRating:0});
 const save=vi.spyOn(ratingService,'rateAnime').mockResolvedValue({});
 render(<MemoryRouter><LanguageProvider><LogoWiggleProvider><Rate/></LogoWiggleProvider></LanguageProvider></MemoryRouter>);
 const stars=await screen.findAllByRole('button',{name:'4점'});
 expect(screen.queryByRole('slider')).toBeNull();
 expect(screen.queryByText(/Invalid Date/)).toBeNull();
 expect(screen.getByText('2014 · TV 시리즈')).toBeTruthy();
 stars.forEach(s=>expect(s.closest('a')).toBeNull());
 expect(screen.getByRole('link',{name:'캐릭터'}).getAttribute('href')).toBe('/rate-characters');
 stars[0].getBoundingClientRect=()=>({left:0,width:40,top:0,height:40});
 fireEvent.click(stars[0],{clientX:30});
 await waitFor(()=>expect(save).toHaveBeenCalledWith(1,{rating:4,status:'RATED'}));
 expect(await screen.findAllByText('평가완료')).toBeTruthy();
});
